// Runs the meeting-publisher job inside the app, replacing the launchd agent
// (com.madcactus.meeting-publisher). One pass = spawn the bundled Bun sidecar
// on the bundled tools/meeting-publisher/publish.ts, with config + state in
// the app data dir. The script owns all business logic, retries and its own
// state/log; this module only schedules, configures and reports.
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::mpsc::{self, RecvTimeoutError};
use std::sync::Mutex;
use std::thread;
use std::time::Duration;

use serde::{Deserialize, Serialize};
use tauri::{AppHandle, Manager};

const PASS_EVERY: Duration = Duration::from_secs(60);
const OLD_STATE: &str = ".madcactus/meeting-publisher/state";
const OLD_PLIST: &str = "Library/LaunchAgents/com.madcactus.meeting-publisher.plist";

#[derive(Serialize, Deserialize)]
struct Config {
	url: String,
	#[serde(rename = "apiKey")]
	api_key: String,
}

/// Tray → pass loop "run now" signal.
pub struct Publisher {
	tx: Mutex<std::sync::mpsc::Sender<()>>,
}

impl Publisher {
	pub fn sync_now(&self) {
		let _ = self.tx.lock().unwrap().send(());
	}
}

pub fn data_dir(app: &AppHandle) -> PathBuf {
	app.path()
		.app_data_dir()
		.unwrap_or_else(|_| PathBuf::from("."))
}

fn state_dir(app: &AppHandle) -> PathBuf {
	data_dir(app).join("meeting-publisher").join("state")
}

fn home() -> PathBuf {
	std::env::var_os("HOME")
		.map(PathBuf::from)
		.unwrap_or_default()
}

// ── one-time migration from the launchd install ────────────────────

pub fn seed(app: &AppHandle) {
	let dir = data_dir(app);
	if let Err(e) = fs::create_dir_all(&dir) {
		log::error!("cannot create data dir {}: {e}", dir.display());
		return;
	}

	// State first: without pushed.txt every historical meeting would re-push.
	let state = state_dir(app);
	let old = home().join(OLD_STATE);
	if !state.join("pushed.txt").exists() && old.exists() {
		match copy_dir(&old, &state) {
			Ok(()) => log::info!("migrated publisher state from {}", old.display()),
			Err(e) => log::error!("state migration from {} failed: {e}", old.display()),
		}
	}

	// Config: seed from the launchd plist while it still exists.
	let cfg = dir.join("config.json");
	if !cfg.exists() {
		let plist = home().join(OLD_PLIST);
		if let Some((url, key)) = fs::read_to_string(&plist).ok().and_then(|txt| {
			plist_str(&txt, "MADCACTUS_URL").zip(plist_str(&txt, "MADCACTUS_API_KEY"))
		}) {
				match serde_json::to_string_pretty(&Config {
					url,
					api_key: key,
				}) {
					Ok(json) => match fs::write(&cfg, json + "\n") {
						Ok(()) => log::info!("seeded config.json from {}", plist.display()),
						Err(e) => log::error!("writing config.json: {e}"),
					},
					Err(e) => log::error!("serializing config: {e}"),
				}
		}
	}
}

/** The plist is generated by our own template — a flat key/string scan is
 *  enough; no plist crate for two values. */
fn plist_str(plist: &str, key: &str) -> Option<String> {
	let marker = format!("<key>{key}</key>");
	let rest = &plist[plist.find(&marker)?..];
	let start = rest.find("<string>")? + "<string>".len();
	let end = start + rest[start..].find("</string>")?;
	Some(rest[start..end].trim().to_string())
}

fn copy_dir(src: &Path, dst: &Path) -> std::io::Result<()> {
	fs::create_dir_all(dst)?;
	for entry in fs::read_dir(src)? {
		let entry = entry?;
		let target = dst.join(entry.file_name());
		if entry.path().is_dir() {
			copy_dir(&entry.path(), &target)?;
		} else {
			fs::copy(entry.path(), target)?;
		}
	}
	Ok(())
}

// ── scheduling ──────────────────────────────────────────────────────

pub fn spawn_loop(app: AppHandle) {
	let (tx, rx) = mpsc::channel::<()>();
	app.manage(Publisher { tx: Mutex::new(tx) });
	thread::spawn(move || loop {
		run_pass(&app);
		match rx.recv_timeout(PASS_EVERY) {
			Ok(()) => {} // sync-now: run the next pass immediately
			Err(RecvTimeoutError::Timeout) => {}
			Err(RecvTimeoutError::Disconnected) => break,
		}
	});
}

fn run_pass(app: &AppHandle) {
	let config = match load_config(app) {
		Some(c) => c,
		None => {
			log::error!(
				"no config.json in {} — publisher idle. Add {{\"url\", \"apiKey\"}} there (tray → Open data folder).",
				data_dir(app).display()
			);
			return;
		}
	};
	let (Some(bun), Some(script)) = (bun_path(), publish_script(app)) else {
		log::error!("bun sidecar or publish.ts resource missing — build the app via scripts/fetch-bun.sh");
		return;
	};

	match Command::new(&bun)
		.arg(&script)
		.env("MADCACTUS_URL", &config.url)
		.env("MADCACTUS_API_KEY", &config.api_key)
		.env("PUBLISHER_STATE_DIR", state_dir(app))
		// GUI apps get a minimal PATH — the script shells out to ffprobe (brew).
		.env("PATH", "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin")
		.current_dir(data_dir(app))
		.output()
	{
		// The script logs its own activity to state/log; only surface failures.
		Ok(o) if o.status.success() => {}
		Ok(o) => log::error!(
			"publish.ts exited {:?}: {}",
			o.status.code(),
			String::from_utf8_lossy(&o.stderr).trim()
		),
		Err(e) => log::error!("spawning publisher: {e}"),
	}
}

fn load_config(app: &AppHandle) -> Option<Config> {
	let path = data_dir(app).join("config.json");
	serde_json::from_str(&fs::read_to_string(path).ok()?).ok()
}

/** Sidecar lands next to the main binary. Prod bundles use the
 *  triple-suffixed name; `tauri dev` copies it in as plain `bun`. */
fn bun_path() -> Option<PathBuf> {
	let dir = std::env::current_exe().ok()?.parent()?.to_path_buf();
	let plain = if cfg!(windows) { "bun.exe" } else { "bun" };
	[dir.join(bun_sidecar()), dir.join(plain)]
		.into_iter()
		.find(|p| p.exists())
}

fn bun_sidecar() -> &'static str {
	#[cfg(all(target_os = "macos", target_arch = "aarch64"))]
	{
		"bun-aarch64-apple-darwin"
	}
	#[cfg(all(target_os = "macos", target_arch = "x86_64"))]
	{
		"bun-x86_64-apple-darwin"
	}
	#[cfg(all(target_os = "windows", target_arch = "x86_64"))]
	{
		"bun-x86_64-pc-windows-msvc.exe"
	}
	#[cfg(all(target_os = "linux", target_arch = "x86_64"))]
	{
		"bun-x86_64-unknown-linux-gnu"
	}
	#[cfg(all(target_os = "linux", target_arch = "aarch64"))]
	{
		"bun-aarch64-unknown-linux-gnu"
	}
}

/** Bundled flat at resource_dir()/publish.ts (map-form resource). Dev
 *  fallback runs it straight from the repo checkout. */
fn publish_script(app: &AppHandle) -> Option<PathBuf> {
	if let Ok(rd) = app.path().resource_dir() {
		let p = rd.join("publish.ts");
		if p.exists() {
			return Some(p);
		}
	}
	Path::new(env!("CARGO_MANIFEST_DIR"))
		.join("../../tools/meeting-publisher/publish.ts")
		.canonicalize()
		.ok()
		.filter(|p| p.is_file())
}
